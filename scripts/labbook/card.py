"""Assemble the whole card for one theme."""

from datetime import datetime

from anim import CYCLE, Anims
from chart import render_chart
from footer import render_footer, summary
from header import render_header
from layout import H, MONO, SANS, W, WEEKS
from legend import render_legend
from log import render_log
from model import Entry
from svg import esc
from weeks import bucket


def render_card(entries: list[Entry], user: str, now: datetime, p: dict[str, str]) -> str:
    anims = Anims()
    log = render_log(entries, now, anims)
    chart = render_chart(bucket(entries, now.date(), WEEKS), anims)
    keyframes = "\n      ".join(anims.rules)
    desc = (f"{summary(entries)}. The newest appear one line at a time on the left; "
            f"the right shows how many merged each week for the last {WEEKS} weeks, by area of work.")
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="t d">
  <title id="t">{esc(user)}'s lab notebook</title>
  <desc id="d">{esc(desc)}</desc>
  <!-- Generated by scripts/labbook; edit the code there, not here. -->
  <defs>
    <style>
      .cmd {{ font: 500 15px {MONO}; fill: {p["text"]}; }}
      .accent {{ fill: {p["accent"]}; }}
      .label {{ font: 700 13px {MONO}; fill: {p["muted"]}; letter-spacing: 1px; text-transform: uppercase; }}
      .rule {{ stroke: {p["track"]}; stroke-width: 1; }}
      .ref {{ font: 500 12px {MONO}; fill: {p["muted"]}; }}
      .title {{ font: 500 14px {SANS}; fill: {p["text"]}; }}
      .small {{ font: 500 11px {MONO}; fill: {p["muted"]}; }}
      .tiny {{ font: 500 10px {MONO}; fill: {p["muted"]}; }}
      .track {{ fill: {p["panel"]}; }}
      .cursor {{ fill: {p["accent"]}; }}

      .a {{ animation-duration: {CYCLE:g}s; animation-iteration-count: infinite; animation-timing-function: ease-out; }}
      .grow {{ transform-box: fill-box; transform-origin: bottom; }}
      {keyframes}

      @media (prefers-reduced-motion: reduce) {{ * {{ animation: none !important; }} }}
    </style>
  </defs>

  <rect width="{W}" height="{H}" rx="16" fill="{p["bg"]}" stroke="{p["track"]}"/>
  {render_header(user)}
  {log}
  {chart}
  {render_legend(entries)}
  {render_footer(entries, now.date())}
</svg>
'''
